function normalizePageVisibility(
    visibility: boolean|AppearancePageVisibility|
    undefined): AppearancePageVisibility {
  if (visibility === undefined) {
    return {
      bookmarksBar: true,
      homeButton: true,
      hoverCard: true,
      pageZoom: true,
      setTheme: true,
      sidePanel: true,
    };
  }

  if (typeof visibility === 'boolean') {
    return {
      bookmarksBar: visibility,
      homeButton: visibility,
      hoverCard: visibility,
      pageZoom: visibility,
      setTheme: visibility,
      sidePanel: visibility,
    };
  }

  return visibility;
}

