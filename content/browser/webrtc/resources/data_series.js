// The maximum number of data points buffered for each stats. Old data points
// will be shifted out when the buffer is full.
export const MAX_STATS_DATA_POINT_BUFFER_SIZE = 1000;

// Small and non-numeric series use a JS ring. Once enough numeric samples have
// arrived, a GC-managed Wasm array holds 32-bit millisecond offsets. Constant
// series need no value array. There is no linear memory or shared allocator.
const PACK_AT = 256;
let packedOperations;

function getPackedOperations() {
  if (typeof WebAssembly === 'undefined') {
    return null;
  }
  if (packedOperations === undefined) {
    // Generated by tools/optimium/generate_rtc_series_wasm.cjs.
    const bytes = Uint8Array.fromBase64(
        'AGFzbQEAAAABMQhefwFgAn9/AWQAYAJkAH8Bf2ADZAB/fwBefAFgAnx/AWQEYAJkBH8BfGADZAR/fAADBwYBAgMFBgcHNwYGbmV3STMyAAAGZ2V0STMyAAEGc2V0STMyAAIGbmV3RjY0AAMGZ2V0RjY0AAQGc2V0RjY0AAUKQQYJACAAIAH7BgALCQAgACAB+wsACwsAIAAgASAC+w4ACwkAIAAgAfsGBAsJACAAIAH7CwQLCwAgACABIAL7DgQL');
    try {
      packedOperations =
          new WebAssembly.Instance(new WebAssembly.Module(bytes)).exports;
    } catch (error) {
      if (!(error instanceof WebAssembly.CompileError)) {
        throw error;
      }
      // Wasm compilation can be disabled by browser policy.
      packedOperations = null;
    }
  }
  return packedOperations;
}

function isInt32(value) {
  return Object.is(value, value | 0);
}

function fitsOffset(time, origin) {
  const delta = time - origin;
  return delta === (delta | 0);
}

/**
 * A TimelineDataSeries collects an ordered series of (time, value) pairs,
 * and converts them to graph points.  It also keeps track of its color and
 * current visibility state.
 * It keeps MAX_STATS_DATA_POINT_BUFFER_SIZE data points at most. Old data
 * points will be dropped when it reaches this size.
 */
export class TimelineDataSeries {
  constructor(statsType) {
    this.points_ = [];  // Interleaved timestamps and values in physical order.
    this.head_ = 0;
    this.count_ = 0;
    this.offsets_ = null;
    this.numbers_ = null;
    this.integerValues_ = false;
    this.origin_ = 0;
    this.constant_ = 0;

    // Default color.  Should always be overridden prior to display.
    this.color_ = 'red';
    // Whether or not the data series should be drawn.
    this.isVisible_ = true;

    this.cacheStartTime_ = null;
    this.cacheStepSize_ = 0;
    this.cacheValues_ = null;
    this.statsType_ = statsType;
  }

  /**
   * @override
   */
  toJSON() {
    if (!this.count_) {
      return {};
    }

    const values = [];
    for (let i = 0; i < this.count_; ++i) {
      values.push(this.valueAt_(i));
    }
    return {
      startTime: new Date(this.timeAt_(0)),
      endTime: new Date(this.timeAt_(this.count_ - 1)),
      statsType: this.statsType_,
      values: JSON.stringify(values),
    };
  }

  /**
   * Adds a DataPoint to |this| with the specified time and value.
   * DataPoints are assumed to be received in chronological order.
   */
  addPoint(timeTicks, value) {
    // Preserve Date's conversion of strings, fractional and invalid dates.
    const time = Number.isSafeInteger(timeTicks) && Math.abs(timeTicks) <= 8.64e15 ?
        timeTicks : new Date(timeTicks).getTime();
    if (!this.offsets_ && this.count_ === PACK_AT && typeof value === 'number') {
      this.tryPack_();
    }
    if (this.offsets_ &&
        (typeof value !== 'number' || !fitsOffset(time, this.origin_))) {
      this.unpack_();
    }

    const slot = this.slot_(this.count_);
    if (this.count_ === MAX_STATS_DATA_POINT_BUFFER_SIZE) {
      this.head_ = this.slot_(1);
    } else {
      ++this.count_;
    }
    if (this.offsets_) {
      this.writePacked_(slot, time, value);
    } else {
      this.points_[2 * slot] = time;
      this.points_[2 * slot + 1] = value;
    }
    this.cacheValues_ = null;
  }

  slot_(index) {
    return (this.head_ + index) % MAX_STATS_DATA_POINT_BUFFER_SIZE;
  }

  timeAt_(index) {
    const slot = this.slot_(index);
    return this.offsets_ ?
        this.origin_ + packedOperations.getI32(this.offsets_, slot) :
        this.points_[2 * slot];
  }

  valueAt_(index) {
    const slot = this.slot_(index);
    if (!this.offsets_) {
      return this.points_[2 * slot + 1];
    }
    if (!this.numbers_) {
      return this.constant_;
    }
    return this.integerValues_ ? packedOperations.getI32(this.numbers_, slot) :
                                 packedOperations.getF64(this.numbers_, slot);
  }

  tryPack_() {
    const points = this.points_;
    const origin = points[0];
    for (let i = 0; i < points.length; i += 2) {
      if (!fitsOffset(points[i], origin) || typeof points[i + 1] !== 'number') {
        return;
      }
    }
    const ops = getPackedOperations();
    if (!ops) {
      return;
    }
    this.origin_ = origin;
    this.constant_ = points[1];
    this.offsets_ = ops.newI32(0, MAX_STATS_DATA_POINT_BUFFER_SIZE);
    for (let i = 0; i < this.count_; ++i) {
      this.writePacked_(i, points[2 * i], points[2 * i + 1]);
    }
    this.points_ = null;
  }

  writePacked_(slot, time, value) {
    packedOperations.setI32(this.offsets_, slot, time - this.origin_);
    if (!this.numbers_) {
      if (Object.is(value, this.constant_)) {
        return;
      }
      this.integerValues_ = isInt32(this.constant_) && isInt32(value);
      const allocate = this.integerValues_ ? packedOperations.newI32 :
                                            packedOperations.newF64;
      this.numbers_ = allocate(this.constant_, MAX_STATS_DATA_POINT_BUFFER_SIZE);
    }
    if (this.integerValues_) {
      if (isInt32(value)) {
        packedOperations.setI32(this.numbers_, slot, value);
        return;
      }
      // Widen the physical ring once, retaining even signed zero exactly.
      const previous = this.numbers_;
      this.numbers_ = packedOperations.newF64(0, MAX_STATS_DATA_POINT_BUFFER_SIZE);
      for (let i = 0; i < this.count_; ++i) {
        packedOperations.setF64(this.numbers_, i, packedOperations.getI32(previous, i));
      }
      this.integerValues_ = false;
    }
    packedOperations.setF64(this.numbers_, slot, value);
  }

  unpack_() {
    const points = [];
    for (let i = 0; i < this.count_; ++i) {
      points.push(this.timeAt_(i), this.valueAt_(i));
    }
    this.head_ = 0;
    this.points_ = points;
    this.offsets_ = this.numbers_ = null;
  }

  isVisible() {
    return this.isVisible_;
  }

  show(isVisible) {
    this.isVisible_ = isVisible;
  }

  getColor() {
    return this.color_;
  }

  setColor(color) {
    this.color_ = color;
  }

  getCount() {
    return this.count_;
  }
  /**
   * Returns a list containing the values of the data series at |count|
   * points, starting at |startTime|, and |stepSize| milliseconds apart.
   * Caches values, so showing/hiding individual data series is fast.
   */
  getValues(startTime, stepSize, count) {
    // Use cached values, if we can.
    if (this.cacheValues_ && this.cacheStartTime_ === startTime &&
        this.cacheStepSize_ === stepSize &&
        this.cacheValues_.length === count) {
      return this.cacheValues_;
    }

    // Do all the work.
    this.cacheValues_ = this.getValuesInternal_(startTime, stepSize, count);
    this.cacheStartTime_ = startTime;
    this.cacheStepSize_ = stepSize;

    return this.cacheValues_;
  }

  /**
   * Returns the cached |values| in the specified time period.
   */
  getValuesInternal_(startTime, stepSize, count) {
    const values = [];
    let nextPoint = 0;
    let time = startTime;
    let nextTime = this.count_ ? this.timeAt_(0) : Infinity;
    let previousValue = 0;
    for (let i = 0; i < count; ++i) {
      let currentValue = null;
      let numPoints = 0;
      while (nextPoint < this.count_ && nextTime < time) {
        // In case multiple dataPoints exist within the `stepSize`,
        // get the average in that interval.
        currentValue += this.valueAt_(nextPoint);
        ++nextPoint;
        if (nextPoint < this.count_) {
          nextTime = this.timeAt_(nextPoint);
        }
        ++numPoints;
      }
      values[i] =
        (currentValue == null) ? previousValue : (currentValue / numPoints);
      previousValue = values[i];
      time += stepSize;
    }
    return values;
  }
}
